-- fledge's Hyprland config: https://wiki.hypr.land/Configuring/Start/
-- Keep this file tiny. An error in it is Hyprland's emergency mode (only
-- SUPER+Q terminal, SUPER+R run, SUPER+M exit); an error in any file it loads
-- costs just that file's settings and shows a notification (fledge/load.lua).
-- Later files override earlier ones.
local found, load = pcall(require, "fledge.load")
if not found then
  -- fledge/load.lua missing or broken, e.g. a reload that ran mid-way through a
  -- git pull or restow: a minimal stand-in, so the rest still loads instead of
  -- Hyprland falling back to emergency mode. The next reload picks the real
  -- one up again.
  local err = load
  local function notify(what, e)
    -- First line only: a failed require lists every path it tried.
    local text = "fledge: " .. what .. ": " .. tostring(e):match("^[^\n]*")
    io.stderr:write(text, "\n")
    -- All inside the pcall: even reading hl.notification may fail.
    pcall(function()
      hl.notification.create({ text = text, timeout = 15000, icon = "error", color = "rgb(ff5555)" })
    end)
  end
  load = {
    notify = notify,
    file = function(path)
      local f = io.open(path, "r")
      if not f then return nil end
      f:close()
      local ok, res = pcall(dofile, path)
      if not ok then notify(path, res) end
      return ok, res
    end,
    dir = function(dir) -- every *.lua in dir, sorted: the feature toggles
      local ls = io.popen("ls -1 -- '" .. dir:gsub("'", "'\\''") .. "' 2>/dev/null")
      if not ls then return true end
      local names = {}
      for name in ls:lines() do
        if name:match("%.lua$") then names[#names + 1] = name end
      end
      ls:close()
      table.sort(names)
      for _, name in ipairs(names) do load.file(dir .. "/" .. name) end
      return true
    end,
  }
  notify("fledge/load.lua", err)
end
local home = os.getenv("HOME")
local fledge = home .. "/.config/hypr/fledge/"

load.file(fledge .. "envs.lua")
load.file(fledge .. "looknfeel.lua")
load.file(fledge .. "misc.lua")
load.file(fledge .. "rules.lua")
load.file(fledge .. "switcher.lua")

-- The current theme's colours: a table, e.g. { activeBorderColor = "rgb(f4af03)" }.
local ok, theme = load.file(home .. "/.config/omarchy/current/theme/hyprland.lua")
if ok and type(theme) == "table" and theme.activeBorderColor then
  local applied, err = pcall(hl.config, {
    general = { col = { active_border = theme.activeBorderColor } },
    group = { col = { border_active = theme.activeBorderColor } },
  })
  if not applied then load.notify("theme colours", err) end
end

-- Binds, monitors, workspace pins, input and per-app window rules, generated by `fledge settings apply`
-- from ~/.config/fledge/settings.json. Change them in the settings window (Super+K).
local gen = home .. "/.local/state/fledge/hypr/"
if load.file(gen .. "binds.lua") ~= true then
  -- binds.lua missing or broken: enough binds to get help or get out, rather
  -- than none. `fledge settings apply` (Super+K's settings window saves with it)
  -- writes binds.lua again.
  for _, b in ipairs({
    { "SUPER + RETURN", "Terminal", "uwsm app -- $TERMINAL" },
    { "SUPER + SPACE", "Launch apps", "qs -c fledge ipc call launcher toggle" },
    { "SUPER + K", "Keybinds", "qs -c fledge ipc call settings open keybinds" },
    { "SUPER + ESCAPE", "System menu", "qs -c fledge ipc call launcher open system" },
    { "SUPER + M", "Exit Hyprland" },
  }) do
    pcall(function()
      hl.bind(b[1], b[3] and hl.dsp.exec_cmd(b[3]) or hl.dsp.exit(), { description = b[2] })
    end)
  end
end
-- apps.lua after rules.lua (loaded above), so Settings › Apps wins over it.
for _, name in ipairs({ "input", "monitors", "workspaces", "apps" }) do
  load.file(gen .. name .. ".lua")
end

-- Feature toggles switched on and off by fledge hyprland toggle.
load.dir(home .. "/.local/state/hypr-toggles")

