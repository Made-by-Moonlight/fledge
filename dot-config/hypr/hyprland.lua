-- fledge's Hyprland config: https://wiki.hypr.land/Configuring/Start/
-- Keep this file tiny. An error in it is Hyprland's emergency mode (only
-- SUPER+Q terminal, SUPER+R run, SUPER+M exit); an error in any file it loads
-- costs just that file's settings and shows a notification (fledge/load.lua).
-- Later files override earlier ones.
local found, load = pcall(require, "fledge.load")
if not found then
  -- fledge/load.lua missing or broken, e.g. for a moment during a git pull or
  -- restow while Hyprland auto-reloads: a minimal stand-in, so the rest still
  -- loads instead of Hyprland falling back to emergency mode. The next reload
  -- picks the real one up again.
  local err = load
  local function notify(what, e)
    -- First line only: a failed require lists every path it tried.
    local text = "fledge: " .. what .. ": " .. tostring(e):match("^[^\n]*")
    io.stderr:write(text, "\n")
    pcall(hl.notification.create, { text = text, timeout = 15000, icon = "error", color = "rgb(ff5555)" })
  end
  load = {
    notify = notify,
    file = function(path)
      local f = io.open(path, "r")
      if not f then return nil end
      f:close()
      local ok, res = pcall(dofile, path)
      if not ok then notify(path, res) end
      return ok, res
    end,
    dir = function() return true end,
  }
  notify("fledge/load.lua", err)
end
local home = os.getenv("HOME")
local fledge = home .. "/.config/hypr/fledge/"

load.file(fledge .. "envs.lua")
load.file(fledge .. "looknfeel.lua")
load.file(fledge .. "misc.lua")
load.file(fledge .. "rules.lua")

-- The current theme's colours: a table, e.g. { activeBorderColor = "rgb(f4af03)" }.
local ok, theme = load.file(home .. "/.config/omarchy/current/theme/hyprland.lua")
if ok and type(theme) == "table" and theme.activeBorderColor then
  local applied, err = pcall(hl.config, {
    general = { col = { active_border = theme.activeBorderColor } },
    group = { col = { border_active = theme.activeBorderColor } },
  })
  if not applied then load.notify("theme colours", err) end
end

-- Binds, monitors, workspace pins and input, generated by `mbm settings apply`
-- from ~/.config/mbm/settings.json. Change them in the settings window (Super+K).
for _, name in ipairs({ "binds", "input", "monitors", "workspaces" }) do
  load.file(home .. "/.local/state/mbm/hypr/" .. name .. ".lua")
end

-- Feature toggles switched on and off by slievr-hyprland-toggle.
load.dir(home .. "/.local/state/hypr-toggles")

load.file(fledge .. "autostart.lua")
