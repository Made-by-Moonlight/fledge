#!/usr/bin/env bash
# Unit tests for bootstrap.sh's remove_hypr_stub, taken out of the script on its
# own (bootstrap.sh itself installs packages and stows; never run it here).
#   bash cachyos/test-bootstrap.sh
set -uo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=SCRIPTDIR/install/test/lib.sh
source "$DIR/install/test/lib.sh"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT

fn="$(sed -n '/^remove_hypr_stub() {/,/^}/p' "$DIR/bootstrap.sh")"
check "found remove_hypr_stub in bootstrap.sh" "yes" "$([[ -n $fn ]] && echo yes || echo no)"
eval "$fn"

STUB=$'\n\n# This config is a STUB! This should never be generated.\n# Use the default lua config\n\nautogenerated = 1\n'
# case <stub|mine|tracked-stub|late-marker> <in_session> <lua_session>: prints kept/removed
case_() {
  local r="$T/r"; rm -rf "$r"; git init -q "$r"; mkdir -p "$r/dot-config/hypr"
  local f="$r/dot-config/hypr/hyprland.conf"
  case $1 in
    stub) printf '%s' "$STUB" >"$f" ;;
    mine) printf '# my own config\nmonitor = , preferred, auto, 1\n' >"$f" ;;
    tracked-stub) printf '%s' "$STUB" >"$f"; git -C "$r" add dot-config/hypr/hyprland.conf ;;
    # the marker past the first 200 bytes: not Hyprland's stub (autostart.lua reads no further)
    late-marker) { printf '#%.0s' {1..250}; printf '\n%s' "$STUB"; } >"$f" ;;
    none) ;;
  esac
  remove_hypr_stub "$r" "$2" "$3"; local rc=$?
  echo "rc=$rc $([[ -e $f ]] && echo kept || echo gone)"
}

check "untracked stub, no session: removed" "rc=0 gone" "$(case_ stub "" "")"
check "untracked stub, Lua session: removed" "rc=0 gone" "$(case_ stub 1 1)"
check "untracked stub, .conf session running: kept (it would write it again)" "rc=0 kept" "$(case_ stub 1 "")"
check "a hyprland.conf without the marker: kept" "rc=0 kept" "$(case_ mine "" "")"
check "a tracked stub: kept" "rc=0 kept" "$(case_ tracked-stub "" "")"
check "marker past the first 200 bytes: kept" "rc=0 kept" "$(case_ late-marker "" "")"
check "no hyprland.conf: fine" "rc=0 gone" "$(case_ none "" "")"

# hypr_manager: which config manager the running Hyprland has, from how a stub
# fledge answers `hypr eval 'return 1'`.
fn="$(sed -n '/^hypr_manager() {/,/^}/p' "$DIR/bootstrap.sh")"
check "found hypr_manager in bootstrap.sh" "yes" "$([[ -n $fn ]] && echo yes || echo no)"
eval "$fn"
mkfledge() { # mkfledge <rc> <output>: a stub fledge
  printf '#!/usr/bin/env bash\nprintf "%%s\\n" %q >&2\nexit %s\n' "$2" "$1" >"$T/fledge"; chmod +x "$T/fledge"
}
mkfledge 0 ""
check "eval answered: lua" "lua" "$(hypr_manager "$T/fledge")"
mkfledge 1 "fledge hypr: eval is only supported with the lua config manager"
check "the .conf manager's refusal: conf" "conf" "$(hypr_manager "$T/fledge")"
mkfledge 1 $'fledge hypr: HYPRLAND_INSTANCE_SIGNATURE was not set!\nmore'
check "any other failure: unknown, with the first line of why" \
  "unknown: fledge hypr: HYPRLAND_INSTANCE_SIGNATURE was not set!" "$(hypr_manager "$T/fledge")"
contains "no fledge at all: unknown" "unknown: " "$(hypr_manager "$T/nope")"

# shellcheck disable=SC2154 # $fail comes from lib.sh
exit $fail
